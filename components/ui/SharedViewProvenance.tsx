'use client';

import * as React from 'react';
import { Button } from '@patternfly/react-core';
import Link from 'next/link';

export interface SharedViewProvenanceProps {
  /** Simulator that produced the numbers in the shared view. */
  sharedSimulator: string;
  /** Simulator this profile is using right now. */
  currentSimulator: string;
  /** Catalog entries, so an id this build has never heard of keeps its own name. */
  simulators: ReadonlyArray<{ id: string; label: string }>;
  /** Switch this view only; saved settings keep their simulator. */
  onUseShared: () => void;
}

/**
 * Tell the reader that a shared view was generated by a different simulator.
 *
 * The page never switches silently. Both names are spelled out, and the only
 * action offered is a view-local switch, so a recipient's saved settings are
 * left exactly as they were.
 */
export function SharedViewProvenance({
  sharedSimulator,
  currentSimulator,
  simulators,
  onUseShared,
}: SharedViewProvenanceProps) {
  const label = (id: string) =>
    simulators.find(entry => entry.id === id)?.label ?? id;

  return (
    <div
      role="status"
      style={{
        display: 'flex',
        flexWrap: 'wrap',
        alignItems: 'center',
        gap: '8px 12px',
        padding: '12px 16px',
        marginBottom: '16px',
        border: '1px solid var(--gc-link)',
        borderRadius: '8px',
        background: '#e7f4ff',
        color: 'var(--gc-text)',
        fontSize: '14px',
      }}
    >
      <span>
        This view was shared using <strong>{label(sharedSimulator)}</strong>; your
        settings use <strong>{label(currentSimulator)}</strong>.
      </span>
      <Button variant="link" onClick={onUseShared}>
        Use {label(sharedSimulator)} for this view
      </Button>
      <Link href="/settings">Open settings</Link>
    </div>
  );
}
