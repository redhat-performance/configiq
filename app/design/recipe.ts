import type { Candidate } from "@/lib/types/pareto";

/** Build a vLLM CLI args YAML or llm-d ModelService YAML for a candidate. */
export function buildRecipe(candidate: Candidate, format: "vllm" | "llmd"): string {
  const tp = candidate.topology.tp ?? candidate.topology.prefill?.tp ?? 1;
  const pp = candidate.topology.pp ?? candidate.topology.prefill?.pp ?? 1;
  const mode = candidate.mode;
  const isDisagg = mode === "disagg" || mode === "disaggregated";

  if (format === "vllm") {
    return buildVllmRecipe(candidate, tp as number, pp as number, isDisagg);
  }
  return buildLlmdRecipe(candidate, tp as number, pp as number, isDisagg);
}

function buildVllmRecipe(candidate: Candidate, tp: number, pp: number, isDisagg: boolean): string {
  const lines: string[] = [
    `# vLLM serve recipe — ${candidate.candidate_id}`,
    `# Generated by ConfigIQ on ${new Date().toISOString().split("T")[0]}`,
    `# Mode: ${candidate.mode} | GPUs: ${candidate.used_gpus ?? "unknown"}`,
    `#`,
    `# Usage: vllm serve <model_path> $(cat this-file.yaml | yq -r 'to_entries[] | "--" + .key + " " + (.value | tostring)' | tr '\\n' ' ')`,
    ``,
    `tensor_parallel_size: ${tp}`,
    `pipeline_parallel_size: ${pp}`,
  ];

  if (isDisagg) {
    const prefillWorkers = candidate.topology.prefill?.workers ?? 1;
    const decodeWorkers = candidate.topology.decode?.workers ?? 1;
    const decodeTp = candidate.topology.decode?.tp ?? tp;
    const decodePp = candidate.topology.decode?.pp ?? pp;
    lines.push(
      ``,
      `# Disaggregated P/D configuration`,
      `# Prefill pool: ${prefillWorkers} worker(s), TP=${tp}, PP=${pp}`,
      `# Decode pool: ${decodeWorkers} worker(s), TP=${decodeTp}, PP=${decodePp}`,
      `kv_transfer_config:`,
      `  kv_connector: PyNcclConnector`,
      `  kv_role: kv_both`,
    );
    if (candidate.transfer_delay_modeled) {
      lines.push(`  # Transfer modeled at 25 GB/s (RoCE 200G)`);
    }
  }

  lines.push(
    ``,
    `# Provenance: ${candidate.provenance_sources.join(", ") || "aisimulate"}`,
    `# Objectives: throughput_per_user=${candidate.objectives?.throughput_per_user?.toFixed(2) ?? "n/a"} tok/s, throughput_per_gpu=${candidate.objectives?.throughput_per_gpu?.toFixed(2) ?? "n/a"} tok/s`,
  );

  return lines.join("\n");
}

function buildLlmdRecipe(candidate: Candidate, tp: number, pp: number, isDisagg: boolean): string {
  const name = candidate.candidate_id.replace(/[^a-z0-9-]/g, "-");
  const lines: string[] = [
    `# llm-d ModelService recipe — ${candidate.candidate_id}`,
    `# Generated by ConfigIQ on ${new Date().toISOString().split("T")[0]}`,
    ``,
    `apiVersion: inference.llm-d.ai/v1alpha1`,
    `kind: ModelService`,
    `metadata:`,
    `  name: ${name}`,
    `spec:`,
    `  model: ""  # fill in your model path`,
    `  decodeDeployment:`,
    `    tensorParallelSize: ${isDisagg ? (candidate.topology.decode?.tp ?? tp) : tp}`,
    `    pipelineParallelSize: ${isDisagg ? (candidate.topology.decode?.pp ?? pp) : pp}`,
    `    replicas: ${isDisagg ? (candidate.topology.decode?.workers ?? 1) : 1}`,
  ];

  if (isDisagg) {
    lines.push(
      `  prefillDeployment:`,
      `    tensorParallelSize: ${tp}`,
      `    pipelineParallelSize: ${pp}`,
      `    replicas: ${candidate.topology.prefill?.workers ?? 1}`,
    );
    if (candidate.transfer_delay_modeled) {
      lines.push(
        `  kvTransfer:`,
        `    bandwidthGbPerSecond: 25.0  # RoCE 200G`,
      );
    }
  }

  lines.push(
    `  # Candidate: ${candidate.candidate_id}`,
    `  # GPUs total: ${candidate.used_gpus ?? "unknown"}`,
    `  # Provenance: ${candidate.provenance_sources.join(", ") || "aisimulate"}`,
  );

  return lines.join("\n");
}
